def wav_bytes(frequency=1000, amplitude=0.01, duration=0.6, split_frequency=None):
    rate = 48000
    samples = [int(amplitude * 32767 * math.sin(2 * math.pi * (
        split_frequency if split_frequency and index < rate * duration / 2 else frequency
    ) * index / rate)) for index in range(round(rate * duration))]
    output = io.BytesIO()
    with wave.open(output, 'wb') as wav:
        wav.setparams((1, 2, rate, len(samples), 'NONE', 'not compressed'))
        wav.writeframes(struct.pack('<' + 'h' * len(samples), *samples))
    return output.getvalue()


